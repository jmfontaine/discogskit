"""Generate the agent skill's references from the code, so they can't drift from it.

- ``commands.md`` from the CLI's own parameters, as ``--help`` reports them.
- ``schemas.md`` from each entity's Arrow schemas, with the column types each writer maps them to.
- ``ddl.md`` from the statements the SQLite and PostgreSQL writers run.

Run ``just skill-references`` after changing a command, an option, a schema or a writer's DDL;
``tests/test_skills.py`` fails while a committed reference differs from what this script generates.
``--check`` only reports the stale files, exiting 1 when there are any.
"""

from __future__ import annotations

import inspect
import sys
from pathlib import Path

import typer
from typer.core import TyperArgument, TyperGroup

from discogskit.cli import app
from discogskit.entities import ENTITIES
from discogskit.writers import postgresql, sqlite

REFERENCES = (
    Path(__file__).parent.parent
    / "src"
    / "discogskit"
    / "skills"
    / "core"
    / "references"
)

_NOTE = (
    "<!-- Generated by scripts/skill_references.py: run `just skill-references` "
    "instead of editing. -->"
)


def _help_text(text: str) -> str:
    """Help text on one line, as Markdown list items need it."""
    return " ".join(text.split())


def _command(ctx: typer.Context) -> list[str]:
    """The Markdown section for ``ctx``'s command, then one per subcommand when it's a group."""
    cmd = ctx.command
    lines = [f"## `{ctx.command_path}`", ""]
    if cmd.help:
        lines += [inspect.cleandoc(cmd.help), ""]
    # Joined here rather than taken from get_usage(), which wraps at the terminal's width.
    usage = " ".join([ctx.command_path, *cmd.collect_usage_pieces(ctx)])
    lines += ["```text", usage, "```", ""]

    panels: dict[str, list[str]] = {}
    for param in cmd.get_params(ctx):
        record = param.get_help_record(ctx)
        if record is None or "--help" in param.opts:
            continue
        opts, text = record
        if isinstance(param, TyperArgument):
            panel = "Arguments"
        else:
            panel = getattr(param, "rich_help_panel", None) or "Options"
        item = f"- `{opts}`"
        if text:
            item += f": {_help_text(text)}"
        panels.setdefault(panel, []).append(item)
    for panel, items in panels.items():
        lines += [f"{panel}:", "", *items, ""]

    if isinstance(cmd, TyperGroup):
        subs = [
            (name, sub)
            for name in cmd.list_commands(ctx)
            if (sub := cmd.get_command(ctx, name)) is not None
        ]
        lines += ["Commands:", ""]
        lines += [
            f"- `{name}`: {sub.get_short_help_str(limit=200)}" for name, sub in subs
        ]
        lines.append("")
        for name, sub in subs:
            lines += _command(typer.Context(sub, info_name=name, parent=ctx))
    return lines


def render_commands() -> str:
    lines = [
        "# Command reference",
        "",
        _NOTE,
        "",
        "Every command, its arguments and options, as `--help` shows them. Every command also takes `--help`.",
        "",
        *_command(typer.Context(typer.main.get_command(app), info_name="discogskit")),
    ]
    return "\n".join(lines).rstrip("\n") + "\n"


def render_schemas() -> str:
    lines = [
        "# Table schemas",
        "",
        _NOTE,
        "",
        "Each entity's tables, root table first. Parquet files carry the Arrow types; `load` maps them to the",
        "PostgreSQL and SQLite types shown, and JSONL writes the same columns as JSON values. A column that isn't",
        "nullable is never `NULL` (`null` in JSONL).",
    ]
    for entity in ENTITIES.values():
        root, *children = entity.table_order
        lines += ["", f"## {entity.name}", ""]
        lines.append(
            f"`{root}` is the root table, one row per `<{entity.root_tag}>` record, with primary key `id`."
        )
        if entity.fk_column and children:
            lines.append(
                f"Every other table links each row to its record through `{entity.fk_column}` "
                f"(= `{root}.id`), which `load` indexes."
            )
        for table in entity.table_order:
            lines += [
                "",
                f"### {table}",
                "",
                "| Column | Arrow (Parquet) | PostgreSQL | SQLite | Nullable |",
                "|---|---|---|---|---|",
            ]
            lines += [
                f"| `{field.name}` | `{field.type}` "
                f"| `{postgresql._arrow_to_pg_type(field.type).as_string(None)}` "
                f"| `{sqlite._arrow_to_sqlite_type(field.type)}` "
                f"| {'yes' if field.nullable else 'no'} |"
                for field in entity.schemas[table]
            ]
    return "\n".join(lines) + "\n"


def _with_fk_comment(line: str, fk_line: str) -> str:
    """``line`` of the plain CREATE TABLE, with what ``--fk`` adds to it (``fk_line``) as a trailing comment."""
    base, extra = line.rstrip(","), fk_line.rstrip(",")
    if base == extra:
        return line
    if not extra.startswith(base):
        raise ValueError(f"--fk changes {base.strip()!r} beyond appending to it")
    return f"{line}  -- with --fk: {extra.removeprefix(base).strip()}"


def render_ddl() -> str:
    lines = [
        "# DDL",
        "",
        _NOTE,
        "",
        "The statements `load` runs for each entity, in order. With `--overwrite`, it first drops the entity's",
        "existing tables, in the same transaction that creates them again; the drops are left out here.",
        "",
        "## PostgreSQL",
        "",
        "Tables are created without keys, so the bulk load runs faster; the primary key and the indexes are built",
        "once the rows are written (`--pg-index-workers` builds that many indexes at once), and with `--fk`, the",
        "foreign keys after them. `--pg-unlogged` creates `UNLOGGED` tables. Tables go to the current schema, or the",
        "one `--pg-schema` names. PostgreSQL names each index `<table>_<column>_idx`.",
    ]
    for entity in ENTITIES.values():
        root, *children = entity.table_order
        fk = entity.fk_column
        lines += ["", f"### {entity.name}", "", "```sql"]
        lines += [
            postgresql.generate_ddl(t, entity.schemas[t]).as_string(None) + ";"
            for t in entity.table_order
        ]
        lines += [
            "-- after the rows are written",
            postgresql._primary_key_ddl(root).as_string(None) + ";",
        ]
        if fk and children:
            lines += [
                postgresql._index_ddl(t, fk).as_string(None) + ";" for t in children
            ]
            lines.append("-- with --fk")
            lines += [
                postgresql._foreign_key_ddl(t, fk, root).as_string(None) + ";"
                for t in children
            ]
        lines.append("```")

    lines += [
        "",
        "## SQLite",
        "",
        "Tables are created with their primary key; the indexes are built once the rows are written. With `--fk`,",
        "each table other than the root also declares its foreign key, shown in the comment after its link column.",
    ]
    for entity in ENTITIES.values():
        root, *children = entity.table_order
        fk = entity.fk_column
        lines += ["", f"### {entity.name}", "", "```sql"]
        for t in entity.table_order:
            ddl = sqlite.generate_ddl(t, entity.schemas[t], pk_column="id")
            if fk and t != root:
                with_fk = sqlite.generate_ddl(
                    t,
                    entity.schemas[t],
                    fk_column=fk,
                    fk_ref_table=root,
                    pk_column="id",
                )
                ddl = "\n".join(
                    _with_fk_comment(line, fk_line)
                    for line, fk_line in zip(
                        ddl.splitlines(), with_fk.splitlines(), strict=True
                    )
                )
            lines.append(ddl + ";")
        if fk and children:
            lines.append("-- after the rows are written")
            lines += [sqlite._index_ddl(t, fk) + ";" for t in children]
        lines.append("```")
    return "\n".join(lines) + "\n"


GENERATED = {
    "commands.md": render_commands,
    "ddl.md": render_ddl,
    "schemas.md": render_schemas,
}


def main(argv: list[str]) -> int:
    check = argv == ["--check"]
    if argv and not check:
        print("usage: skill_references.py [--check]", file=sys.stderr)
        return 2
    stale = []
    for name, render in GENERATED.items():
        path = REFERENCES / name
        text = render()
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(name)
        if not check:
            path.write_text(text, encoding="utf-8")
    if check and stale:
        print(
            f"Stale: {', '.join(stale)}. Run `just skill-references`.", file=sys.stderr
        )
        return 1
    for name in stale:
        print(f"Wrote references/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
